def _checked(fn, args: dict, project) -> dict:
    """Run a sub-command and project it, or return a compact error."""
    try:
        return project(fn(dict(args)))
    except Exception as error:  # noqa: BLE001  # one error per check, never a raise
        return {"error": f"{type(error).__name__}: {error}"}


def cmd_gate(args: dict) -> dict:
    """The terminal gate in one call: dry + ruff + format + pytest + acceptance.

    Returns one compact verdict for each requested check, plus `pass`.
    checks defaults to all five. Example: swarm.gate({subsystem, feature})
    """
    checks = args.get("checks") or ["dry", "ruff", "format", "pytest", "acceptance"]
    if args.get("crap") and "crap" not in checks:
        checks = [*checks, "crap"]
    out: dict = {}

    def verdict(r: dict, keep: list[str]) -> dict:
        """One check's compact result plus the command's own ok verdict."""
        return {**{key: r.get(key) for key in keep}, "ok": bool(r.get("ok"))}

    if "dry" in checks:
        out["dry"] = _checked(
            cmd_dry,
            args,
            lambda r: verdict(r, ["total", "exit"]),
        )
    if "ruff" in checks:
        out["ruff"] = _checked(
            cmd_ruff,
            args,
            lambda r: verdict(r, ["total", "byCode", "exit"]),
        )
    if "format" in checks:
        out["format"] = _checked(
            cmd_format,
            args,
            lambda r: verdict(r, ["total", "exit"]),
        )
    if "pytest" in checks:
        out["pytest"] = _checked(
            cmd_pytest,
            args,
            lambda r: {
                **verdict(r, ["passed", "failed", "errors", "exit"]),
                "failures": [f["test"] for f in r.get("failures", [])],
            },
        )
    if "acceptance" in checks:
        out["acceptance"] = _checked(
            cmd_acceptance,
            args,
            lambda r: {
                **verdict(r, ["passed", "failed", "exit"]),
                "failures": [f["test"] for f in r.get("failures", [])],
            },
        )
    if "crap" in checks:
        from swarm_quality import cmd_crap

        out["crap"] = _checked(
            cmd_crap,
            args,
            lambda r: verdict(r, ["above", "exit"]),
        )
    out["pass"] = all(v.get("ok") for v in out.values() if isinstance(v, dict))
    return out


def cmd_ready(args: dict) -> dict:
    """The record gate in one call: check + lint-record + decisions.

    checks defaults to all three. Example: swarm.ready({role:"architect", subsystem})
    """
    checks = args.get("checks") or ["check", "record", "decisions"]
    out: dict = {}

    def verdict(r: dict, keep: list[str]) -> dict:
        """One check's compact result plus the command's own ok verdict."""
        return {**{key: r.get(key) for key in keep}, "ok": bool(r.get("ok"))}

    if "check" in checks:
        out["check"] = _checked(
            cmd_check,
            args,
            lambda r: verdict(r, ["passed", "errors", "warnings", "byCode"]),
        )
    if "record" in checks:
        out["record"] = _checked(
            cmd_lint_record,
            args,
            lambda r: verdict(r, ["passed", "errors", "warnings"]),
        )
    if "decisions" in checks:
        out["decisions"] = _checked(cmd_decisions, args, lambda r: verdict(r, ["open"]))
    out["pass"] = all(isinstance(v, dict) and bool(v.get("ok")) for v in out.values())
    return out


def _write_union_skeleton(root, subsystem: str, counts: dict):
    """Project the subsystem `SKELETON.md` from the module skeletons.

    One home for the contracts: `modules/<module>/SKELETON.md`. This file is a
    generated concatenation of those files, plus the cross-module brief of the
    critic. A hand copy of a contract drifts, so no role retypes one.

    A HAND-WRITTEN union is never overwritten. It carries the critic's cross-module
    synthesis, which the projection does not rebuild, so a blind overwrite would lose
    it. The projection claims the file only when it is absent or already generated.
    """
    out_path = root / "SKELETON.md"
    if out_path.is_file():
        existing = out_path.read_text(encoding="utf-8")
        if "GENERATED by swarm.genRecord" not in existing:
            return None  # a hand-written union stands; the critic owns it
    mod_root = root / "modules"
    if not mod_root.is_dir():
        return None
    mods = sorted(
        p for p in mod_root.iterdir() if p.is_dir() and (p / "SKELETON.md").is_file()
    )
    flat = sorted(p for p in mod_root.glob("*.md"))
    if not mods and not flat:
        return None
    brief_path = root / "04-critic" / "3-skeleton.md"
    brief = (
        brief_path.read_text(encoding="utf-8").strip() if brief_path.is_file() else ""
    )
    if not brief:
        review = root / "review.md"
        brief = review.read_text(encoding="utf-8").strip() if review.is_file() else ""
    names = [p.name for p in mods] + [p.stem for p in flat]
    body = [
        f"# SKELETON — {subsystem}",
        "",
        "<!-- GENERATED by swarm.genRecord from the module contracts. Do not hand-edit. -->",
        "",
        "The whole brief for the coder and the refactorer. The contracts live once, in",
        "`modules/<module>.md`. The frozen interface text is in `architecture.md`.",
        "",
        f"- modules: {', '.join(names)}",
        f"- interfaces: design/subsystems/{subsystem}/architecture.md",
        (
            f"- counts: {counts['classes']} classes, {counts['ops']} ops,"
            f" {counts['edges']} edges (from model.json)"
        ),
        "",
    ]
    if brief:
        body += ["## Cross-module brief", "", brief, ""]
    for mod in mods:
        text = (mod / "SKELETON.md").read_text(encoding="utf-8").strip()
        body += [f"## MODULE — {mod.name}", "", text, ""]
    for path in flat:
        body += [
            f"## MODULE — {path.stem}",
            "",
            path.read_text(encoding="utf-8").strip(),
            "",
        ]
    out = root / "SKELETON.md"
    out.write_text("\n".join(body), encoding="utf-8")
    return out


def cmd_gen_record(args: dict) -> dict:
    """Project `SKELETON.md` from the module contracts, and return model counts.

    Counts are returned as data, never written as a second document. The record
    keeps one copy of each contract: `modules/<module>.md`.
    """
    subsystem = args.get("subsystem")
    if not subsystem:
        raise SwarmError("pass subsystem")
    root = PACK / "design" / "subsystems" / str(subsystem)
    model_path = root / "model.json"
    if not model_path.exists():
        raise SwarmError(f"no model.json at {_short(model_path)}")
    model = json.loads(model_path.read_text(encoding="utf-8"))
    classes = [
        cls for pkg in model.get("packages", []) for cls in pkg.get("classes", [])
    ]
    ops = [op for cls in classes for op in cls.get("ops", [])]

    def is_command(op) -> bool:
        cqs = (op.get("annotations") or {}).get("cqs") or "query"
        return str(cqs).lower() == "command"

    commands = [op for op in ops if is_command(op)]
    queries = [op for op in ops if not is_command(op)]
    counts = {
        "classes": len(classes),
        "ops": len(ops),
        "commands": len(commands),
        "queries": len(queries),
        "edges": len(model.get("edges", [])),
        "levels": len(model.get("levels", [])),
    }
    skeleton_out = _write_union_skeleton(root, str(subsystem), counts)
    result = {
        "subsystem": subsystem,
        "model": _short(model_path),
        "skeleton": _short(skeleton_out) if skeleton_out else None,
        **counts,
    }
    if skeleton_out is None:
        union = root / "SKELETON.md"
        if union.is_file():
            result["skeleton"] = _short(union)
            result["note"] = (
                "the union SKELETON.md is the critic's; genRecord left it alone. "
                "Write the cross-module brief in 04-critic/3-skeleton.md, then delete "
                "SKELETON.md to let the projection claim it."
            )
    return result


def cmd_report(args: dict) -> dict:
    """Report the session cost per role, from the OpenCode database.

    Reads `opencode_db.py`, which opens the database read-only. The rework count
    is the number of sessions per role past the first for one subsystem.
    """
    import opencode_db

    path = opencode_db.db_path(args.get("db"))
    try:
        connection = opencode_db.connect(str(path))
    except FileNotFoundError as error:
        raise SwarmError(str(error)) from error
    rows = opencode_db.session_rows(connection)
    connection.close()
    rows.sort(key=lambda row: row.get("time_created") or 0, reverse=True)
    agg: dict = {}
    for row in rows[:400]:
        agent = row.get("agent")
        if agent is None:
            continue
        entry = agg.setdefault(
            str(agent), {"out": 0, "reason": 0, "sessions": 0, "minutes": 0.0}
        )
        entry["out"] += row.get("tokens_output") or 0
        entry["reason"] += row.get("tokens_reasoning") or 0
        entry["sessions"] += 1
        created = row.get("time_created") or 0
        updated = row.get("time_updated") or created
        entry["minutes"] += max(0.0, (updated - created) / 60000.0)
    for entry in agg.values():
        entry["minutes"] = round(entry["minutes"], 1)
    return {"db": _short(path), "roles": agg}


_MODEL = re.compile(r"(?P<provider>[^/#]+)/(?P<model>[^#]+)(?:#(?P<variant>[^#]+))?$")


def _declared_variants() -> dict:
    """The model variants declared under `providers` in the workspace opencode.json."""
    config = PACK.parent / "opencode.json"
    declared: dict = {}
    if not config.is_file():
        return declared
    try:
        document = json.loads(config.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return declared
    for provider in (document.get("providers") or {}).values():
        for model, spec in (provider.get("models") or {}).items():
            declared[model] = {
                str(variant.get("id"))
                for variant in (spec.get("variants") or [])
                if variant.get("id")
            }
    return declared


def _model_checks() -> list[dict]:
    """The agent model ids are well formed, and any declared variant exists."""
    config = PACK.parent / "opencode.json"
    agents = sorted((PACK.parent / ".opencode" / "agents").glob("*.md"))
    checks: list[dict] = []
    default = None
    if config.is_file():
        try:
            default = json.loads(config.read_text(encoding="utf-8")).get("model")
        except (json.JSONDecodeError, OSError):
            checks.append(
                {"check": "opencode.json", "ok": False, "detail": "cannot parse"}
            )
    declared = _declared_variants()
    unverified = set()
    malformed = []
    for path in agents:
        match = re.search(
            r"^model:\s*(\S+)\s*$", path.read_text(encoding="utf-8"), re.MULTILINE
        )
        model_id = match.group(1) if match else ""
        parsed = _MODEL.match(model_id)
        if parsed is None:
            malformed.append(f"{path.stem}:{model_id or '(none)'}")
            continue
        model, variant = parsed.group("model"), parsed.group("variant")
        if model in declared and variant and variant not in declared[model]:
            malformed.append(f"{path.stem}:{model_id}: variant is not declared")
        elif model not in declared:
            unverified.add(model_id)
    checks.append(
        {
            "check": "agent models",
            "ok": not malformed,
            "detail": "; ".join(malformed)
            or f"{len(agents)} agents, default {default or '(none)'}",
        }
    )
    if unverified:
        checks.append(
            {
                "check": "model variants",
                "ok": True,
                "detail": "not declared in opencode.json, not verifiable offline: "
                + ", ".join(sorted(unverified)),
            }
        )
    return checks


def cmd_doctor(args: dict) -> dict:
    """Check the wiring, the toolchain, and the agent model plan.

    Returns one {check, ok, detail} row per item and a single `pass`. A red row
    names the thing to fix; it never writes.
    """
    paths = _paths()
    checks: list[dict] = []
    checks.append(
        {
            "check": "python",
            "ok": sys.version_info >= (3, 10),
            "detail": sys.version.split()[0],
        }
    )
    for label, path, is_file in (
        ("PACK", paths.pack_root(), False),
        ("CONFIG", paths.config_path(), True),
        ("WORKSPACE", paths.workspace_root(), False),
    ):
        target = Path(path)
        checks.append(
            {
                "check": label,
                "ok": target.is_file() if is_file else target.is_dir(),
                "detail": _short(target),
            }
        )
    for label, root in (("SPECS", paths.specs()), ("FEATURES", paths.features())):
        configured = root.is_configured()
        checks.append(
            {
                "check": label,
                "ok": not configured or Path(root.text()).is_dir(),
                "detail": root.text(),
            }
        )
    for source in paths.source_roots():
        checks.append(
            {"check": "SOURCE", "ok": Path(source).is_dir(), "detail": _short(source)}
        )
    for entry in paths.persistent_roots():
        checks.append(
            {
                "check": "PERSIST",
                "ok": Path(entry.path).is_dir(),
                "detail": f"{_short(entry.path)} ({entry.kind})",
            }
        )
    for name, argv in (
        ("pytest", [sys.executable, "-m", "pytest", "--version"]),
        ("ruff", [sys.executable, "-m", "ruff", "--version"]),
        ("coverage", [sys.executable, "-m", "coverage", "--version"]),
    ):
        code, out, err = _run(argv)
        checks.append(
            {
                "check": name,
                "ok": code == 0,
                "detail": (out or err).strip().splitlines()[0] if (out or err) else "",
            }
        )
    for name, required in (("bb", True), ("node", False)):
        found = shutil.which(name)
        checks.append(
            {
                "check": name,
                "ok": bool(found) or not required,
                "detail": found
                or ("not on PATH (optional)" if not required else "not on PATH"),
            }
        )
    checks.extend(_model_checks())
    return {
        "lane": (os.environ.get("SWARM_LANE") or "").strip() or None,
        "checks": checks,
        "pass": all(check["ok"] for check in checks),
    }
